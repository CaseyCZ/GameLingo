#!/usr/bin/env python3
"""Generate both native mobile contracts from shared/mobile-ui.json.

Edit the shared JSON, then run: python3 tools/sync_mobile_ui.py
CI uses --check to prevent one mobile app from silently diverging.
Never runs against Google TV source or changes console/translation engines.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "shared/mobile-ui.json"
SWIFT = ROOT / "ios/GameLingoIOS/App/GameLingoUIContract.swift"
KOTLIN = ROOT / "tools/GameLingoUIContract.kt"


def quote(value):
    return json.dumps(value, ensure_ascii=False)


def generated_swift(contract):
    out = [
        "// Generated by tools/sync_mobile_ui.py from shared/mobile-ui.json.",
        "// Do not edit directly. Re-generate after reviewing shared UI changes.",
        "enum GameLingoUIContract {",
        "    struct Tab { let title: String; let symbol: String }",
        "    static let tabs: [Tab] = [",
    ]
    out += [
        f"        Tab(title: {quote(t['title'])}, symbol: {quote(t['swift'])}),"
        for t in contract["tabs"]
    ]
    out += [
        "    ]",
        "    static let setupSteps: [String] = [",
    ]
    out += [f"        {quote(v)}," for v in contract["setupSteps"]]
    out += [
        "    ]",
        "    static let settingsSections: [String] = [",
    ]
    out += [f"        {quote(v)}," for v in contract["settingsSections"]]
    out += ["    ]", "}"]
    return "\n".join(out) + "\n"


def generated_kotlin(contract):
    out = [
        "package cz.titulky.tv",
        "",
        "// Generated by tools/sync_mobile_ui.py from shared/mobile-ui.json.",
        "// Do not edit directly. Re-generate after reviewing shared UI changes.",
        "object GameLingoUIContract {",
        "    data class Tab(val title: String, val glyph: String)",
        "    val tabs: List<Tab> = listOf(",
    ]
    out += [
        f"        Tab({quote(t['title'])}, {quote(t['android'])}),"
        for t in contract["tabs"]
    ]
    out += ["    )", "    val setupSteps: List<String> = listOf("]
    out += [f"        {quote(v)}," for v in contract["setupSteps"]]
    out += ["    )", "    val settingsSections: List<String> = listOf("]
    out += [f"        {quote(v)}," for v in contract["settingsSections"]]
    out += ["    )", "}"]
    return "\n".join(out) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    contract = json.loads(SOURCE.read_text(encoding="utf-8"))
    assert len(contract["tabs"]) == 5
    assert len(contract["setupSteps"]) == 5
    assert len(contract["settingsSections"]) == 4
    files = {
        SWIFT: generated_swift(contract),
        KOTLIN: generated_kotlin(contract),
    }
    for path, expected in files.items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != expected:
                raise SystemExit(f"Stale mobile UI contract: {path}; regenerate with python3 tools/sync_mobile_ui.py")
        else:
            path.write_text(expected, encoding="utf-8")
    print("Shared iOS/Android navigation, onboarding and settings contract:", "CHECK OK" if args.check else "GENERATED")


if __name__ == "__main__":
    main()
