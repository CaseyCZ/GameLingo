#!/usr/bin/env python3
"""Generate native GameLingo UI catalogs from shared/locales/*.json.

Usage: python3 tools/generate_locales.py [--check]
No network, translation API or third-party dependencies. Only UI strings.
Changing OCR source/target languages is deliberately out of scope.
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LOCALES = ROOT / "shared" / "locales"
IOS = ROOT / "ios" / "GameLingoIOS" / "App"
ANDROID = ROOT / "tools" / "GameLingoLanguages.kt"
IOS_LANGUAGE = IOS / "GameLingoAppLanguage.swift"
PROJECT = IOS.parent / "project.yml"
BEGIN_LABELS = "    // BEGIN GENERATED UI LABELS"
END_LABELS = "    // END GENERATED UI LABELS"
BEGIN_ANDROID_LANGUAGES = "    // BEGIN GENERATED APP LANGUAGES"
END_ANDROID_LANGUAGES = "    // END GENERATED APP LANGUAGES"
BEGIN_IOS_LANGUAGES = "    // BEGIN GENERATED UI LANGUAGES"
END_IOS_LANGUAGES = "    // END GENERATED UI LANGUAGES"


def no_duplicates(items):
    result = {}
    for key, value in items:
        if key in result:
            raise ValueError(f"Duplicate translation key: {key!r}")
        result[key] = value
    return result


def load(path):
    return json.loads(path.read_text(encoding="utf-8"), object_pairs_hook=no_duplicates)


def quote(value):
    return json.dumps(value, ensure_ascii=False)


def validate():
    manifest = load(LOCALES / "manifest.json")
    languages = manifest["languages"]
    codes = [entry["code"] for entry in languages]
    if not codes or len(set(codes)) != len(codes):
        raise ValueError("Each UI locale must have a unique code")
    if any(not re.fullmatch(r"[a-z]{2}(?:-[A-Z]{2})?", code) for code in codes):
        raise ValueError("Unsupported locale code")
    if any(not isinstance(item.get("name"), str) or not item["name"].strip()
           for item in languages):
        raise ValueError("Each locale needs its native display name")
    if manifest["source"] != "cs" or manifest["fallback"] != "en":
        raise ValueError("Current source must be Czech and fallback English")
    if "cs" not in codes or "en" not in codes:
        raise ValueError("Czech source and English fallback are required")
    catalogs = {code: load(LOCALES / f"{code}.json") for code in codes}
    keys = set(catalogs["cs"])
    if not keys:
        raise ValueError("Empty UI catalog")
    for code, strings in catalogs.items():
        if set(strings) != keys:
            missing = sorted(keys - set(strings))
            extra = sorted(set(strings) - keys)
            raise ValueError(f"{code}: missing {missing[:8]}, extra {extra[:8]}")
        for key, value in strings.items():
            if not key or not isinstance(value, str) or not value.strip() or "\x00" in value:
                raise ValueError(f"{code}: invalid UI string for {key!r}")
            if key.count("%@") != value.count("%@"):
                raise ValueError(f"{code}: status placeholder mismatch for {key!r}")
            if len(key) > 500 or len(value) > 2000:
                raise ValueError(f"{code}: unexpectedly long UI string: {key[:60]}")
    if any(key != value for key, value in catalogs["cs"].items()):
        raise ValueError("Czech legacy keys must preserve their visible wording")
    return manifest, catalogs


def swift_strings(catalog):
    lines = [
        "/* Generated by tools/generate_locales.py. Edit shared/locales/*.json instead. */",
    ]
    for key in sorted(catalog):
        lines.append(f"{quote(key)} = {quote(catalog[key])};")
    return "\n".join(lines) + "\n"


def between(content, start, end, replacement):
    if content.count(start) != 1 or content.count(end) != 1:
        raise ValueError(f"Missing or repeated generated markers: {start!r}")
    left, remaining = content.split(start, 1)
    _, right = remaining.split(end, 1)
    return left + start + "\n" + replacement + "\n" + end + right


def kotlin_string(value):
    # Kotlin treats dollar signs as template interpolation; JSON strings do not.
    return quote(value).replace("$", r"\$")


def kotlin_labels(languages, catalogs):
    available = [item["code"] for item in languages if item["code"] != "cs"]
    parts = [
        "    private val uiLabels: Map<String, Map<String, String>> by lazy {",
        "        mapOf(",
    ]
    parts += [
        f"            {quote(code)} to labels_{code.replace('-', '_')}(),"
        for code in available
    ]
    parts += ["        )", "    }", ""]
    for code in available:
        suffix = code.replace("-", "_")
        catalog = catalogs[code]
        keys = sorted(catalog)
        parts.extend([
            f"    private fun labels_{suffix}(): Map<String, String> = mutableMapOf<String, String>().apply {{",
        ])
        for i in range(0, len(keys), 180):
            parts.append(f"        fill_{suffix}_{i // 180}(this)")
        parts.extend(["    }", ""])
        for i in range(0, len(keys), 180):
            parts.append(f"    private fun fill_{suffix}_{i // 180}(out: MutableMap<String, String>) {{")
            for key in keys[i:i + 180]:
                parts.append(f"        out[{kotlin_string(key)}] = {kotlin_string(catalog[key])}")
            parts.extend(["    }", ""])
    return "\n".join(parts).rstrip()


def kotlin_language_list(languages):
    parts = ["    val appLanguages = listOf("]
    for item in languages:
        parts.append(f"        Language({quote(item['code'])}, {quote(item['name'])}),")
    parts.append("    )")
    return "\n".join(parts)


def swift_language_list(languages):
    codes = [item["code"] for item in languages]
    parts = ["    private static let supportedCodes = ["]
    parts.extend(f"        {quote(code)}," for code in codes)
    parts.extend(["    ]", "    private static let nativeNames: [String: String] = ["])
    parts.extend(f"        {quote(item['code'])}: {quote(item['name'])}," for item in languages)
    parts.append("    ]")
    return "\n".join(parts)


def outputs(manifest, catalogs):
    generated = {}
    for code, strings in catalogs.items():
        if code != "cs":
            generated[IOS / f"{code}.lproj" / "Localizable.strings"] = swift_strings(strings)
    kt = ANDROID.read_text(encoding="utf-8")
    kt = between(kt, BEGIN_LABELS, END_LABELS,
                 kotlin_labels(manifest["languages"], catalogs))
    kt = between(kt, BEGIN_ANDROID_LANGUAGES, END_ANDROID_LANGUAGES,
                 kotlin_language_list(manifest["languages"]))
    generated[ANDROID] = kt
    swift = IOS_LANGUAGE.read_text(encoding="utf-8")
    swift = between(swift, BEGIN_IOS_LANGUAGES, END_IOS_LANGUAGES,
                    swift_language_list(manifest["languages"]))
    generated[IOS_LANGUAGE] = swift
    project = PROJECT.read_text(encoding="utf-8")
    match = re.search(r"(^\s*CFBundleLocalizations:\s*)\[[^]\n]*\]", project, re.M)
    if not match:
        raise ValueError("Xcode project is missing CFBundleLocalizations")
    native_list = "[" + ", ".join(item["code"] for item in manifest["languages"]) + "]"
    generated[PROJECT] = project[:match.start()] + match.group(1) + native_list + project[match.end():]
    return generated


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true",
                        help="Fail if native catalogs differ from shared source")
    args = parser.parse_args()
    manifest, catalogs = validate()
    generated = outputs(manifest, catalogs)
    stale = [path for path, expected in generated.items()
             if not path.exists() or path.read_text(encoding="utf-8") != expected]
    if args.check:
        if stale:
            raise SystemExit("Generated localization files are stale: " +
                             ", ".join(str(p.relative_to(ROOT)) for p in stale))
    else:
        for path, expected in generated.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected, encoding="utf-8")
    print(f"UI locales: {len(catalogs)} languages, {len(catalogs['cs'])} keys, "
          f"{len(generated)} generated files; " +
          ("CHECK OK" if args.check else "GENERATED"))


if __name__ == "__main__":
    main()
